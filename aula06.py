# conversão de tipos, coerção
# type convertion, typecasting, coercion
# é o ato de converter um tipo em outro
# tipos imutáveis e primitivos:
# str, int, float, bool

print('1', type('1'))
print(int('1'), type(int('1'))) # converter de str pra int.
print(int('1') + 1)
print(bool(' ')) # converter de str pra bool
print(str(11) + 'b') # converter pra str